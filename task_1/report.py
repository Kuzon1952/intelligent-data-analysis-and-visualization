"""Собирает task_1/REPORT.md из тех же функций, что и дашборд: числа в отчёте и на плитках совпадают.

    poetry run python task_1/report.py
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path[:0] = [str(HERE), str(HERE.parent)]

import numpy as np  # noqa: E402

from filters import Filters  # noqa: E402
from src.data_loader import load_cards  # noqa: E402
from src.fmt import ru_duration, ru_int, ru_num, ru_pct  # noqa: E402
from views import summary  # noqa: E402

MONTHS = ["январь", "февраль", "март", "апрель", "май", "июнь", "июль", "август", "сентябрь", "октябрь",
          "ноябрь", "декабрь"]


def month(ts) -> str:
    return f"{MONTHS[ts.month - 1]} {ts.year}"


def build() -> str:
    cards, source = load_cards()
    full = summary(cards, Filters())
    recent = summary(cards, Filters(period="Последние 90 дней"))
    k, kr = full["kpis"], recent["kpis"]
    flow = full["flow"]
    totals = flow.sum(axis=1)
    peak_month = totals.idxmax()
    unlabeled = flow["Без вердикта"]
    unl_months = unlabeled[unlabeled / totals.replace(0, np.nan) > 0.3]
    real_share_m = flow["Реальный инцидент"] / totals.replace(0, np.nan)
    big = (totals >= 1000) & ~totals.index.isin(unl_months.index)  # месяцы с заметным и размеченным потоком
    rules = full["rules"].assign(noise=lambda t: t["cards"] - t["real"]).sort_values("noise", ascending=False)
    rk = full["rules_kpis"]
    react, react_r = full["reaction"], recent["reaction"]
    crit = react.loc["Критическая"]
    lk = full["load_kpis"]
    closing = full["closing"]

    lines: list[str] = []
    add = lines.append
    add("# Отчёт по заданию 1 · Карточки SOC")
    add("")
    add("> Файл собран скриптом `task_1/report.py` из тех же функций, что и дашборд. "
        "Время — московское. Если данные изменятся, отчёт нужно пересобрать.")
    add("")
    add("## Что за данные")
    add("")
    add(f"Набор `{source.name}`: **{ru_int(k['cards'])} карточек** SOC за {ru_int(k['days'])} дней "
        f"({cards['date'].min():%d.%m.%Y} — {cards['date'].max():%d.%m.%Y}), в среднем ≈ {ru_num(k['per_day'], 0)} "
        "в день. Карточка — это алерт SIEM (MaxPatrol или Ankey), который аналитик L1 берёт в работу, "
        "разбирает и закрывает с вердиктом. Вердикты сведены в пять групп: реальный инцидент (`Решён`), "
        "ложное срабатывание (`False Positive`), дубликат, без вердикта (`Не указан`) и прочее.")
    add("")
    add("## Кому и зачем")
    add("")
    add("Дашборд сделан для **руководителя SOC**. Ему нужно за пару минут понять: сколько работы "
        "приходит и сколько в ней пользы, какие правила SIEM стоит доработать, выполняются ли нормативы "
        "по критичности и как распределить смены. Поэтому каждый график отвечает на один управленческий "
        "вопрос, а фильтры (период, критичность, источник SIEM, тип дня) меняют все элементы сразу.")
    add("")
    add("## Главные выводы")
    add("")
    add(f"1. **Большая часть потока — шум.** {ru_pct(k['fp_share'])} карточек закрыты как ложное срабатывание, "
        f"ещё {ru_pct(k['no_verdict_share'])} — без вердикта. Реальных инцидентов {ru_int(k['real'])} "
        f"({ru_pct(k['real_share'])}): соотношение «ложные срабатывания : инциденты» ≈ "
        f"{ru_num(k['fp_share'] / k['real_share'], 1)} : 1.")
    add(f"2. **Почти бесполезные правила корреляции: {rk['noisy_rules']} из {rk['rules']}.** У них меньше 1 % карточек — "
        f"реальные инциденты, а вместе они дают {ru_pct(rk['noisy_share'])} всего потока "
        f"(карточек — {ru_int(rk['noisy_cards'])}). Первые кандидаты на доработку: "
        + ", ".join(f"`{r}`" for r in rk["top_noisy"]) + ".")
    add(f"3. **Приоритет по критичности за весь период не работал.** Медиана взятия в работу у критических "
        f"карточек — {ru_duration(crit['median_s'])} при нормативе {ru_duration(crit['sla_s'])}; у остальных — "
        f"{ru_duration(k['rest_take_median'])}. Норматив нарушен у {ru_pct(crit['breach_share'], 0)} "
        "критических карточек — это худший показатель среди всех уровней.")
    if not react_r.empty:
        add(f"4. **За последние 90 дней картина другая:** нарушений SLA взятия {ru_pct(kr['breach_share'])} "
            f"(за весь период — {ru_pct(k['breach_share'])}), медиана взятия критических — "
            f"{ru_duration(kr['crit_take_median'])}. Норматив для всех уровней в этом окне один — "
            f"{ru_duration(react_r['sla_s'].median())}, поэтому сравнивать периоды нужно с этой оговоркой.")
    add(f"5. **Пик нагрузки — {lk['peak'][0]}, {lk['peak'][1]:02d}:00** (≈ {ru_num(lk['peak_value'], 0)} карточек "
        f"в час); на ночные часы (20:00–08:00) приходится {ru_pct(lk['night_share'], 0)} потока, так что ночная смена нужна.")
    add("")
    add("## Вопросы и почему выбран именно этот график")
    add("")
    add("| # | Вопрос | График | Почему он |")
    add("|---|---|---|---|")
    add("| 1 | Из чего состоит поток карточек и как он менялся? | Столбцы с накоплением по месяцам "
        "(по неделям, если окно ≤ 120 дней), цвет — вердикт | Высота столбца показывает объём, сегменты — состав, "
        "и всё на одной оси времени. Линия потеряла бы состав, круговая диаграмма — динамику. |")
    add("| 2 | Какие правила корреляции создают шум, а не инциденты? | Линейчатая диаграмма с накоплением: "
        "12 правил с наибольшим числом карточек, не ставших инцидентом; справа — доля реальных инцидентов | "
        "Длина — самый точный канал для сравнения, длинные имена правил читаются только по горизонтали. "
        "Подпись справа сразу отвечает «стоит ли это правило своих карточек». |")
    add("| 3 | Берут ли критические карточки в работу быстрее остальных? | «Гантели» по уровням критичности: "
        "норматив SLA, медиана и 90-й процентиль, лог. шкала | Видно сразу три вещи: норматив, типичное время "
        "и хвост. Среднее исказил бы длинный хвост (до суток), а время тянется от секунд до часов — "
        "поэтому шкала логарифмическая. |")
    add("| 4 | Когда приходит нагрузка? | Тепловая карта «день недели × час», среднее число карточек за час | "
        "Два категориальных измерения и одна величина — классический случай для теплокарты. Делим на число "
        "дней, иначе дни, которых в окне больше, выглядели бы загруженнее. |")
    add("| 5 | Сколько живёт карточка до закрытия у самых частых типов? | Полоса 25–75 % и медиана, лог. шкала | "
        "Показывает разброс, а не одно число: у типов с одинаковой медианой может быть разный хвост. |")
    add("")
    add("## Подробно по вопросам")
    add("")
    add("### 1. Состав потока")
    add("")
    add(f"Пик потока — {month(peak_month)} (карточек — {ru_int(totals[peak_month])}). "
        + (f"В первые месяцы ({', '.join(month(m) for m in unl_months.index)}) больше 30 % карточек закрыты "
           "без вердикта — разметка тогда только налаживалась, поэтому доли FP и инцидентов за эти месяцы "
           "занижены. " if len(unl_months) else "")
        + f"В месяцах с размеченным потоком доля реальных инцидентов колеблется от {ru_pct(real_share_m[big].min())} "
        f"({month(real_share_m[big].idxmin())}) до {ru_pct(real_share_m[big].max())} ({month(real_share_m[big].idxmax())}); с конца 2024 года поток стабилизировался на уровне "
        f"≈ {ru_int(totals[totals.index.year == 2025].mean() if (totals.index.year == 2025).any() else totals.mean())} "
        "карточек в месяц.")
    add("")
    add("### 2. Шумные правила")
    add("")
    add("| Правило | Карточек | Не инцидент | Доля реальных инцидентов |")
    add("|---|---:|---:|---:|")
    for name, row in rules.head(8).iterrows():
        add(f"| `{name}` | {ru_int(row['cards'])} | {ru_int(row['noise'])} | {ru_pct(row['real_share'])} |")
    add("")
    add("Карточки без правила корреляции (ручной ввод, почта, часть сетевых сенсоров) собраны в строку "
        "`(без правила)`. Правила с числом карточек меньше 50 в анализ не входят: доля инцидентов на малых "
        "числах слишком нестабильна.")
    add("")
    add("### 3. Скорость взятия в работу")
    add("")
    add("| Критичность | Карточек с датой взятия | Норматив | Медиана | 90-й процентиль | Вне SLA |")
    add("|---|---:|---:|---:|---:|---:|")
    for level, row in react.iterrows():
        add(f"| {level} | {ru_int(row['with_take'])} | {ru_duration(row['sla_s'])} | {ru_duration(row['median_s'])} | "
            f"{ru_duration(row['p90_s'])} | {ru_pct(row['breach_share'])} |")
    add("")
    add("Самый строгий норматив — у критических карточек, но именно их берут в работу медленнее всех. "
        "Возможная причина — критические карточки сложнее и требуют подготовки, однако по нормативу SOC "
        "это не оправдание: стоит проверить, попадают ли они в отдельную очередь.")
    add("")
    add("### 4. Нагрузка по часам")
    add("")
    add(f"Нагрузка концентрируется в будни с 09:00 до 17:00, максимум — {lk['peak'][0]} в {lk['peak'][1]:02d}:00. "
        f"Ночью поток не нулевой ({ru_pct(lk['night_share'], 0)}), а доля реальных инцидентов ночью почти "
        "такая же, как днём (видно в подсказке ячейки), поэтому сокращать ночную смену до нуля нельзя.")
    add("")
    add("### 5. Время до закрытия")
    add("")
    add("| Тип инцидента | Карточек | Медиана | 25–75 % | Реальных инцидентов |")
    add("|---|---:|---:|---:|---:|")
    for name, row in closing.sort_values("median", ascending=False).iterrows():
        add(f"| {name} | {ru_int(row['cards'])} | {ru_duration(row['median'])} | "
            f"{ru_duration(row['q25'])} – {ru_duration(row['q75'])} | {ru_pct(row['real_share'])} |")
    add("")
    add("## Решения по данным")
    add("")
    add("- **Время взятия** = `Дата взятия в работу` − `Создан`; **время закрытия** = `Дата закрытия (факт)` − "
        "`Создан`. Отрицательные интервалы (взятие раньше создания) — ошибка выгрузки, они исключаются, "
        "а не превращаются в ноль.")
    add("- **Нарушение SLA** считается заново: время взятия больше норматива `SLA по взятию в работу Атаки` "
        "(в миллисекундах). Флаг `SLA просрочен` в выгрузке заполнен не у всех карточек.")
    add(f"- **Карточки без даты взятия** ({ru_pct(1 - cards['take_s'].notna().mean())} набора) не входят в вопрос 3: "
        "их закрыли, не взяв в работу, и «нулевое» время исказило бы медиану.")
    add("- **Окна периода** считаются от последней даты в данных, а не от сегодняшнего дня.")
    add("- **Мультизначные поля** (`Тип инцидента`, `Пиктограмма IRP`) хранят значения через `~~||~~`; "
        "для разрезов берётся первое значение.")
    add("- **Тип дня** берётся из производственного календаря `calendar.parquet` (праздники не смешаны с буднями).")
    add("")
    return "\n".join(lines)


if __name__ == "__main__":
    text = build()
    (HERE / "REPORT.md").write_text(text, encoding="utf-8")
    print(f"Записан {HERE / 'REPORT.md'} ({len(text.splitlines())} строк)")
