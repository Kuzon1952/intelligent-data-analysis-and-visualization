"""Собирает task_2/REPORT.md из тех же функций, что и дашборд.

    poetry run python task_2/report.py
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path[:0] = [str(HERE), str(HERE.parent)]

import numpy as np  # noqa: E402

from data import load  # noqa: E402
from filters import Filters  # noqa: E402
from src.fmt import ru_int, ru_num, ru_pct  # noqa: E402
from views import summary  # noqa: E402


def thr(x: float) -> str:
    return ru_num(x, 2)


def build() -> str:
    inf = load()
    s = summary(inf, Filters(threshold=inf.threshold))
    c = s["confusion"]
    curve = s["curve"]
    seg = s["segments"]
    weekly = s["weekly"].dropna(subset=["miss_rate"])
    cal = s["calibration"]
    lat = s["latency"]
    labeled = inf.labeled

    by_cat = seg["Категория"]
    by_vendor = seg["Вендор"]
    worst_cat = by_cat[by_cat["reliable"]].sort_values("miss_rate", ascending=False)
    worst_vendor = by_vendor[by_vendor["reliable"]].sort_values("miss_rate", ascending=False)
    bad_weeks = weekly.index[weekly["miss_rate"] > 0.4]
    over = cal[(cal["predicted"] - cal["actual"]) > 0.1]

    lines: list[str] = []
    add = lines.append
    add("# Отчёт по заданию 2 · Можно ли доверять модели-советчику SOC")
    add("")
    add("> Файл собран скриптом `task_2/report.py` из тех же функций, что и дашборд. "
        f"Порог модели — {thr(inf.threshold)} (в `model_params` записан порог 0,82 для класса «FP», "
        "то есть тревога поднимается при оценке вероятности инцидента ≥ 0,18).")
    add("")
    add("## Что за данные")
    add("")
    add(f"`{inf.source.name}` — лог работы модели в режиме советчика: {ru_int(inf.total)} прогонов с "
        f"{labeled['date'].min():%d.%m.%Y} по {labeled['date'].max():%d.%m.%Y}. Для каждой карточки есть оценка "
        "модели (`y_pred_proba`), её решение (`y_pred`) и итоговый вердикт аналитика (`y`: 1 — инцидент, 0 — ложное "
        f"срабатывание). В метрики входят только размеченные карточки — **{ru_int(len(labeled))}**; без разметки "
        f"{ru_int(inf.unlabeled)}, спам и дубликаты {ru_int(inf.excluded)} исключены, иначе precision и recall были бы искажены.")
    add("")
    add("## Кому и зачем")
    add("")
    add("Зритель — **руководство SOC**, не специалисты по машинному обучению. Поэтому на дашборде нет AUC и F1: "
        "все метрики сформулированы как ответы на вопросы руководителя — «сколько инцидентов мы потеряем», "
        "«сколько работы модель снимет», «где ей нельзя верить». Главная метрика по условию задания — "
        "**доля пропущенных реальных инцидентов**, ей отдана красная плитка и красная клетка матрицы.")
    add("")
    add("## Ответ на главный вопрос")
    add("")
    add(f"**Как советчику, который сортирует очередь, — доверять можно; как фильтру, после которого карточки "
        f"не смотрят, — нельзя.** При пороге {thr(inf.threshold)} модель отдаёт аналитикам "
        f"{ru_pct(c['flag_share'], 0)} карточек и ловит {ru_pct(c['recall'])} реальных инцидентов, но "
        f"**пропускает {ru_int(c['fn'])} из {ru_int(c['incidents'])} ({ru_pct(c['miss_rate'])})**. "
        f"В «спокойной» стопке ({ru_pct(c['cleared_share'], 0)} карточек) каждая ≈ {ru_int(1 / c['fn_in_cleared'])}-я — "
        "реальный инцидент, и такие пропуски сосредоточены в конкретных категориях и источниках.")
    add("")
    add("## Вопросы и почему выбран именно этот график")
    add("")
    add("| # | Вопрос руководителя | График | Почему он |")
    add("|---|---|---|---|")
    add("| 1 | Как часто модель соглашается с вердиктом аналитика? | Матрица ошибок словами: «пойман / пропущен / "
        "ложная тревога / верно отсеяно» с числами и долями | Четыре клетки понятны без обучения; одна общая «точность» "
        "скрыла бы, что ошибки бывают разной цены. Пропуск — красная клетка. |")
    add("| 2 | Сколько инцидентов модель пропустит и сколько работы снимет при другом пороге? | Две линии от порога: "
        "доля пропущенных инцидентов и доля карточек для аналитиков; ползунок двигает порог на всём дашборде | "
        "Это цена решения в одном взгляде: каждая точка — компромисс «риск ↔ нагрузка». ROC-кривая для этой аудитории "
        "непонятна. |")
    add("| 3 | Ошибается ли модель случайно или систематически? | Линейчатая: доля пропущенных инцидентов по "
        "сегменту (категория, вендор, критичность, правило — переключатель), пунктир — среднее | Если бы ошибки были "
        "случайны, все столбцы были бы около пунктира. Подпись «X из Y» показывает, на скольких инцидентах основан вывод. |")
    add("| 4 | Стабильна ли модель во времени? | Столбцы с накоплением по неделям: пойманные и пропущенные инциденты, "
        "над столбцом — доля пропусков | Видно и объём инцидентов, и качество — без второй оси. |")
    add("| 5 | Можно ли верить «проценту риска»? | Калибровочная кривая: оценка модели против фактической доли "
        "инцидентов, пунктир — идеал | Руководителю показывают «риск 70 %» — график отвечает, что за ним стоит на деле. |")
    add("")
    add("## Подробно по вопросам")
    add("")
    add("### 1. Согласие с аналитиком")
    add("")
    add("| | Модель: тревога | Модель: спокойно |")
    add("|---|---:|---:|")
    add(f"| **Аналитик: инцидент** | {ru_int(c['tp'])} — пойман | **{ru_int(c['fn'])} — пропущен** |")
    add(f"| **Аналитик: ложное срабатывание** | {ru_int(c['fp'])} — ложная тревога | {ru_int(c['tn'])} — верно отсеяно |")
    add("")
    add(f"Решение модели совпадает с вердиктом аналитика в {ru_pct(c['agreement'])} случаев, но эта цифра "
        "обманчива: ложных срабатываний в потоке намного больше, чем инцидентов, и модель, которая всегда говорит "
        f"«спокойно», совпадала бы в {ru_pct(1 - c['incidents'] / c['n'])} случаев. Поэтому важнее другое: "
        f"из тревог модели реальны только {ru_pct(c['precision'])}, а {ru_pct(c['miss_rate'])} инцидентов она не заметила.")
    add("")
    add("### 2. Порог: риск против нагрузки")
    add("")
    add("| Порог | Пропущено инцидентов | Карточек аналитикам | Из тревог — реальные |")
    add("|---:|---:|---:|---:|")
    for t in (0.05, 0.10, inf.threshold, 0.30, 0.50):
        row = curve.iloc[(curve["threshold"] - t).abs().argmin()]
        mark = " (модель)" if abs(t - inf.threshold) < 1e-9 else ""
        add(f"| {thr(row['threshold'])}{mark} | {ru_pct(row['miss_rate'])} | {ru_pct(row['flag_share'])} | "
            f"{ru_pct(row['precision'])} |")
    add("")
    best = s["for_10pct"]
    if best is not None:
        add(f"Чтобы пропускать не больше 10 % инцидентов, порог нужно опустить до ≈ {thr(best['threshold'])} — "
            f"но тогда аналитикам уйдёт {ru_pct(best['flag_share'], 0)} карточек вместо {ru_pct(c['flag_share'], 0)}. "
            + ("Пропуска меньше 5 % нельзя добиться ни при каком пороге ≥ 0,01: часть инцидентов модель оценивает "
               "почти в ноль. Значит, проблему не решить подбором порога — нужна доработка признаков для «слепых» "
               "сегментов (вопрос 3)." if s["for_5pct"] is None else ""))
    add("")
    add("### 3. Систематические ошибки")
    add("")
    add("Модель ошибается **не случайно**. Худшие сегменты (только те, где ≥ 10 реальных инцидентов):")
    add("")
    add("| Разрез | Сегмент | Инцидентов | Пропущено | Доля пропусков |")
    add("|---|---|---:|---:|---:|")
    for name, row in worst_cat.head(4).iterrows():
        add(f"| категория | {name} | {ru_int(row['incidents'])} | {ru_int(row['missed'])} | {ru_pct(row['miss_rate'])} |")
    for name, row in worst_vendor.head(3).iterrows():
        add(f"| вендор | {name} | {ru_int(row['incidents'])} | {ru_int(row['missed'])} | {ru_pct(row['miss_rate'])} |")
    add("")
    if len(worst_vendor) and len(worst_cat):
        v0, c0 = worst_vendor.iloc[0], worst_cat.iloc[0]
        add(f"Инциденты от событий **{worst_vendor.index[0]}** модель пропускает почти все "
            f"({ru_int(v0['missed'])} из {ru_int(v0['incidents'])}), в категории **«{worst_cat.index[0]}»** — "
            f"{ru_int(c0['missed'])} из {ru_int(c0['incidents'])}. Это слепые зоны: в обучающих данных таких "
            "инцидентов, вероятно, было мало. Пока они не исправлены, карточки этих сегментов нужно отдавать "
            "аналитикам независимо от оценки модели.")
    add("")
    add("### 4. Стабильность во времени")
    add("")
    add(f"Доля пропусков по неделям (недели, где ≥ 5 инцидентов) колеблется от {ru_pct(weekly['miss_rate'].min(), 0)} "
        f"(неделя с {weekly['miss_rate'].idxmin():%d.%m}) до {ru_pct(weekly['miss_rate'].max(), 0)} "
        f"(неделя с {weekly['miss_rate'].idxmax():%d.%m}). "
        + (f"Больше 40 % инцидентов модель теряла в неделях с {', '.join(f'{d:%d.%m}' for d in bad_weeks)}. "
           if len(bad_weeks) else "")
        + "Качество зависит от того, какие атаки идут на этой неделе, поэтому "
        "долю пропусков нужно мониторить еженедельно, а не проверить один раз при внедрении.")
    add("")
    add("### 5. Калибровка «процента риска»")
    add("")
    add("| Оценка модели | Карточек | Средняя оценка | Реально инцидентов |")
    add("|---|---:|---:|---:|")
    for name, row in cal.iterrows():
        add(f"| {name} | {ru_int(row['cards'])} | {ru_pct(row['predicted'])} | {ru_pct(row['actual'])} |")
    add("")
    if len(over):
        lo, hi = over.index[0].split("–")[0], over.index[-1].split("–")[1]
        add(f"В диапазоне оценок {lo}–{hi} модель **завышает** риск: при оценке около 50 % "
            "инцидентом оказывается примерно каждая третья-четвёртая карточка. На краях шкалы (меньше 5 % и больше "
            "80 %) оценке можно верить. Показывать руководству «процент риска» как вероятность без этой оговорки нельзя.")
    add("")
    add("## Прочее")
    add("")
    add(f"- Модель отвечает быстро: медиана {ru_num(lat['median'], 2)} с, 95 % ответов быстрее {ru_num(lat['p95'], 1)} с — "
        "для советчика в очереди SOC это не узкое место.")
    add("- Метрики считаются по размеченным карточкам (`y` = 0 или 1). Решение модели пересчитывается из оценки "
        "при выбранном пороге; при пороге модели оно совпадает с полем `y_pred` для всех карточек (проверено в тестах).")
    add("- Поля карточки в этом наборе — JSON-массивы (`[\"MTE_T1053\"]`); для разрезов берётся первый элемент.")
    add("")
    return "\n".join(lines)


if __name__ == "__main__":
    text = build()
    (HERE / "REPORT.md").write_text(text, encoding="utf-8")
    print(f"Записан {HERE / 'REPORT.md'} ({len(text.splitlines())} строк)")
